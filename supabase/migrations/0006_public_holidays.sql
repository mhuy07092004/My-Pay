-- Gazetted statewide public holidays for 2026 and 2027.
-- Part-day rows start at `starts_at` (Christmas Eve 18:00 in QLD, 19:00 in SA and NT;
-- New Year's Eve 19:00 in SA and NT). Regional show days and the NSW bank holiday
-- are not statewide, so they are not included.
-- Sources: state government holiday pages and the Fair Work Ombudsman lists
-- for 2026 and 2027, checked November 2026.

alter table public.profiles
  add constraint profiles_state_check
  check (state in ('NSW', 'VIC', 'QLD', 'SA', 'WA', 'TAS', 'ACT', 'NT'));

create table public.public_holidays (
  state text not null check (state in ('NSW', 'VIC', 'QLD', 'SA', 'WA', 'TAS', 'ACT', 'NT')),
  holiday_date date not null,
  name text not null,
  starts_at time,
  primary key (state, holiday_date)
);

alter table public.public_holidays enable row level security;
create policy public_holidays_read on public.public_holidays
  for select to authenticated using (true);
revoke insert, update, delete, truncate on table public.public_holidays from public, anon, authenticated;

