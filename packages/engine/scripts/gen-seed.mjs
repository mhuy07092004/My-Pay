// Generates supabase/migrations/0002_seed_2026_27.sql from the engine's PAYG JSON,
// so the DB and the engine tests share one source of numbers.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const data = JSON.parse(
  readFileSync(new URL('../src/data/payg-2026-27.json', import.meta.url), 'utf8'),
)
const eff = `date '${data.effectiveFrom}'`
const lt = (v) => (v === null ? 'null' : v)

const lines = ['-- Generated by packages/engine/scripts/gen-seed.mjs. Do not edit by hand.', '']

lines.push('insert into public.tax_withholding_coefficients (effective_from, scale, seq, lt, a, b) values')
const w = []
for (const [scale, rows] of Object.entries(data.scales)) {
  rows.forEach((r, i) => w.push(`  (${eff}, ${scale}, ${i}, ${lt(r.lt)}, ${r.a}, ${r.b})`))
}
lines.push(w.join(',\n') + ';', '')

lines.push('insert into public.tax_study_loan_coefficients (effective_from, tbl, seq, lt, a, b) values')
const l = []
for (const [tbl, rows] of [['A', data.loanA], ['B', data.loanB]]) {
  rows.forEach((r, i) => l.push(`  (${eff}, '${tbl}', ${i}, ${lt(r.lt)}, ${r.a}, ${r.b})`))
}
lines.push(l.join(',\n') + ';', '')

lines.push('insert into public.tax_offset_rates (effective_from, cycle, rate) values')
lines.push(
  Object.entries(data.offsetRates)
    .map(([cycle, rate]) => `  (${eff}, '${cycle}', ${rate})`)
    .join(',\n') + ';',
  '',
)

